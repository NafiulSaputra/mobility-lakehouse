"""Repeatable benchmarks (ADR 0013).

- Local: every pipeline step of one month, run several times in one Spark session inside Docker.
- Databricks: task durations of real job runs, read from the Jobs API output of the Databricks CLI.
- Streaming: events per second of the recorded stream runs.

Every report states the machine, the versions and the number of repeats, and gives the median with the
minimum and maximum, so that a reader can judge the spread instead of trusting one number.
"""

from __future__ import annotations

import os
import platform
import statistics
import time
from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import UTC, datetime
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from pyspark.sql import SparkSession

    from mobility_lakehouse.pipeline import Layout
    from mobility_lakehouse.tlc import Month

LOCAL_STEPS = ("bronze", "silver", "gold", "snapshot")


@dataclass(frozen=True)
class StepTiming:
    step: str
    repeat: int
    seconds: float


@dataclass(frozen=True)
class Stats:
    median: float
    minimum: float
    maximum: float
    count: int


def stats(values: list[float]) -> Stats:
    if not values:
        raise ValueError("no values")
    return Stats(statistics.median(values), min(values), max(values), len(values))


def _stats_cells(s: Stats) -> str:
    return f"{format_seconds(s.median)} | {format_seconds(s.minimum)} | {format_seconds(s.maximum)}"


def format_seconds(seconds: float) -> str:
    minutes, rest = divmod(round(seconds), 60)
    return f"{minutes}m {rest:02d}s" if minutes else f"{seconds:.1f}s"


# ---------------------------------------------------------------------------------------------------------
# Local
# ---------------------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class LocalBenchmark:
    month: str
    repeats: int
    timings: tuple[StepTiming, ...]
    rows: dict[str, int]
    environment: dict[str, str]
    measured_at: str

    def step_stats(self, step: str) -> Stats:
        return stats([t.seconds for t in self.timings if t.step == step])

    def total_stats(self) -> Stats:
        per_repeat: dict[int, float] = {}
        for timing in self.timings:
            per_repeat[timing.repeat] = per_repeat.get(timing.repeat, 0.0) + timing.seconds
        return stats(list(per_repeat.values()))


def local_environment(spark: SparkSession) -> dict[str, str]:
    return {
        "CPU cores visible to Spark": str(os.cpu_count()),
        "Spark driver memory": spark.conf.get("spark.driver.memory", "default"),
        "Spark": spark.version,
        "Python": platform.python_version(),
        "OS (inside Docker)": platform.platform(terse=True),
    }


def run_local_benchmark(
    spark: SparkSession,
    layout: Layout,
    month: Month,
    repeats: int = 3,
    clock: Callable[[], float] = time.perf_counter,
) -> LocalBenchmark:
    """Run bronze, silver, gold and snapshot ``repeats`` times.

    Every step replaces the month, so each repeat does the full work and reruns are safe.
    """
    from mobility_lakehouse.pipeline import run_bronze, run_gold, run_silver, run_snapshot

    if repeats < 1:
        raise ValueError("repeats must be at least 1")

    timings: list[StepTiming] = []
    rows: dict[str, int] = {}
    for repeat in range(1, repeats + 1):
        for step in LOCAL_STEPS:
            started = clock()
            if step == "bronze":
                rows["bronze"] = run_bronze(spark, layout, month)
            elif step == "silver":
                rows["silver"] = run_silver(spark, layout, month).silver_rows
            elif step == "gold":
                rows["gold hourly_pickup_zones"] = run_gold(spark, layout, month).rows_per_table[
                    "hourly_pickup_zones"
                ]
            else:
                rows["snapshot hourly_pickup_zones"] = run_snapshot(spark, layout, month)[
                    "hourly_pickup_zones"
                ]
            timings.append(StepTiming(step, repeat, clock() - started))

    return LocalBenchmark(
        month=str(month),
        repeats=repeats,
        timings=tuple(timings),
        rows=rows,
        environment=local_environment(spark),
        measured_at=datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC"),
    )


def render_local(result: LocalBenchmark, streaming: StreamingThroughput | None = None) -> str:
    lines = [
        f"# Local benchmark: {result.month}",
        "",
        f"Generated by `mobility-lakehouse benchmark --month {result.month} --repeats {result.repeats}` on "
        f"{result.measured_at} ([ADR 0013](../adr/0013-benchmark-methodology.md)).",
        "",
        "Each step replaces the month, so every repeat does the full work. All repeats run in one Spark "
        "session: the first repeat includes JVM warm-up, which is why the maximum is usually the first run.",
        "",
        "| Step | Median | Min | Max |",
        "|---|---|---|---|",
    ]
    for step in LOCAL_STEPS:
        s = result.step_stats(step)
        lines.append(f"| {step} | {_stats_cells(s)} |")
    total = result.total_stats()
    lines.append(
        f"| **all four steps** | **{format_seconds(total.median)}** | {format_seconds(total.minimum)} | "
        f"{format_seconds(total.maximum)} |"
    )
    lines += ["", "Rows processed:", "", "| Table | Rows |", "|---|---|"]
    lines += [f"| {name} | {count:,} |" for name, count in result.rows.items()]
    lines += ["", "Environment:", "", "| | |", "|---|---|"]
    lines += [f"| {name} | {value} |" for name, value in result.environment.items()]
    lines += ["", "Every run:", "", "| Repeat | Step | Seconds |", "|---|---|---|"]
    lines += [f"| {t.repeat} | {t.step} | {t.seconds:.1f} |" for t in result.timings]
    if streaming is not None:
        lines += ["", render_streaming(streaming)]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------------------------------------
# Streaming
# ---------------------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class StreamingThroughput:
    runs: int
    events: int
    seconds: float

    @property
    def events_per_second(self) -> float:
        return self.events / self.seconds if self.seconds else 0.0


def streaming_throughput(rows: list[dict[str, Any]]) -> StreamingThroughput | None:
    """Throughput over recorded stream runs that read events (rows of the stream run log)."""
    useful = [r for r in rows if r["input_rows"] and r["finished_at"] > r["started_at"]]
    if not useful:
        return None
    seconds = sum((r["finished_at"] - r["started_at"]).total_seconds() for r in useful)
    return StreamingThroughput(len(useful), sum(int(r["input_rows"]) for r in useful), seconds)


def render_streaming(result: StreamingThroughput) -> str:
    return "\n".join(
        [
            "## Streaming",
            "",
            "From the stream run log (`--until-caught-up` runs, Spark start-up included):",
            "",
            "| Runs | Events read | Wall time | Events per second |",
            "|---|---|---|---|",
            f"| {result.runs} | {result.events:,} | {format_seconds(result.seconds)} | "
            f"{result.events_per_second:,.0f} |",
        ]
    )


def read_stream_runs(spark: SparkSession, runs_path: str) -> list[dict[str, Any]]:
    from delta.tables import DeltaTable

    if not DeltaTable.isDeltaTable(spark, runs_path):
        return []
    rows = spark.read.format("delta").load(runs_path).limit(10_000).collect()
    return [row.asDict() for row in rows]


