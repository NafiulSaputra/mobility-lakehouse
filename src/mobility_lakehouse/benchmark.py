# Databricks
# ---------------------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class DatabricksRun:
    run_id: int
    month: str
    started: str
    seconds: float
    tasks: dict[str, float] = field(default_factory=dict)


def _ms(value: Any) -> int:
    return int(value or 0)


def _succeeded(run: dict[str, Any]) -> bool:
    state = run.get("state") or {}
    if state.get("result_state"):
        return state["result_state"] == "SUCCESS"
    status = run.get("status") or {}
    return (status.get("termination_details") or {}).get("code") == "SUCCESS"


def _month(run: dict[str, Any]) -> str:
    for parameter in run.get("job_parameters") or []:
        if parameter.get("name") == "month":
            return str(parameter.get("value") or parameter.get("default") or "?")
    return "?"


def _task_seconds(task: dict[str, Any]) -> float:
    start, end = _ms(task.get("start_time")), _ms(task.get("end_time"))
    if start and end > start:
        return (end - start) / 1000
    durations = ("setup_duration", "execution_duration", "cleanup_duration")
    return sum(_ms(task.get(d)) for d in durations) / 1000


def parse_databricks_runs(data: Any) -> list[DatabricksRun]:
    """Successful runs from ``databricks jobs list-runs --expand-tasks --output json``.

    Accepts the list the CLI prints, or the API shape ``{"runs": [...]}``.
    """
    runs = data.get("runs", []) if isinstance(data, dict) else list(data or [])
    parsed = []
    for run in runs:
        if not _succeeded(run):
            continue
        start, end = _ms(run.get("start_time")), _ms(run.get("end_time"))
        total = (end - start) / 1000 if start and end > start else _ms(run.get("run_duration")) / 1000
        parsed.append(
            DatabricksRun(
                run_id=int(run.get("run_id", 0)),
                month=_month(run),
                started=datetime.fromtimestamp(start / 1000, UTC).strftime("%Y-%m-%d %H:%M UTC")
                if start
                else "?",
                seconds=total,
                tasks={t.get("task_key", "?"): _task_seconds(t) for t in run.get("tasks") or []},
            )
        )
    return sorted(parsed, key=lambda r: r.started)


def render_databricks(runs: list[DatabricksRun]) -> str:
    if not runs:
        raise ValueError("no successful runs in the input")
    task_names = list(dict.fromkeys(name for run in runs for name in run.tasks))
    lines = [
        "# Databricks benchmark",
        "",
        "Generated by `mobility-lakehouse databricks-timings` from the job run history "
        "([ADR 0013](../adr/0013-benchmark-methodology.md)). Databricks Free Edition, serverless compute, "
        "environment version 5. Task times include serverless start-up.",
        "",
        "| Task | Runs | Median | Min | Max |",
        "|---|---|---|---|---|",
    ]
    for name in task_names:
        s = stats([run.tasks[name] for run in runs if name in run.tasks])
        lines.append(
            f"| {name} | {s.count} | {format_seconds(s.median)} | {format_seconds(s.minimum)} | "
            f"{format_seconds(s.maximum)} |"
        )
    total = stats([run.seconds for run in runs])
    lines.append(
        f"| **whole job** | {total.count} | **{format_seconds(total.median)}** | "
        f"{format_seconds(total.minimum)} | {format_seconds(total.maximum)} |"
    )
    lines += [
        "",
        "Every successful run:",
        "",
        "| Started | Month | Whole job | " + " | ".join(task_names) + " |",
    ]
    lines.append("|---|---|---|" + "---|" * len(task_names))
    for run in runs:
        cells = [format_seconds(run.tasks[name]) if name in run.tasks else "" for name in task_names]
        lines.append(
            f"| {run.started} | {run.month} | {format_seconds(run.seconds)} | " + " | ".join(cells) + " |"
        )
    return "\n".join(lines) + "\n"
